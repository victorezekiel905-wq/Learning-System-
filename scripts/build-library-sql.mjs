// Writes the starter library (supabase/library/starter-lessons.mjs) into migration 1060,
// between its ">>> starter lessons" and "<<< starter lessons" markers. Run: npm run build:sql
import { readFileSync, writeFileSync } from "node:fs";
import { STARTER_LESSONS } from "../supabase/library/starter-lessons.mjs";

const FILE = "supabase/migrations/20260901001060_lesson_library.sql";
const lit = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const rows = STARTER_LESSONS.map((l) => {
  const payload = { default_mode: "live_participation", slides: l.slides.map((s) => (s.kind === "activity"
    ? { kind: "activity", content: {}, notes: null, activity: { kind: s.activity.kind, title: s.activity.title, instructions: null, settings: {},
        questions: s.activity.questions.map((q) => ({ kind: q.kind, prompt: q.prompt, config: {}, answer_key: {}, explanation: q.explanation, points: q.points, tags: [], topic: q.topic, options: q.options })) } }
    : { kind: s.kind, content: s.content, notes: null })) };
  return `  (${lit(l.id)}, ${lit(l.title)}, ${lit(l.subject)}, ${lit(l.level)}, ${lit(l.description)}, ${lit(JSON.stringify(payload))}::jsonb)`;
});
const block = `-- >>> starter lessons (generated by scripts/build-library-sql.mjs from supabase/library/starter-lessons.mjs; do not edit by hand)
insert into public.library_lessons (id, title, subject, level, description, payload) values
${rows.join(",\n")}
on conflict (id) do update set title = excluded.title, subject = excluded.subject, level = excluded.level,
  description = excluded.description, payload = excluded.payload, updated_at = now();
-- <<< starter lessons`;
const sql = readFileSync(FILE, "utf8").replace(/\r\n/g, "\n");
const out = sql.replace(/-- >>> starter lessons[\s\S]*?-- <<< starter lessons/, block);
if (out === sql && !sql.includes("insert into public.library_lessons")) throw new Error("markers not found");
writeFileSync(FILE, out);
console.log(`${FILE}: ${STARTER_LESSONS.length} starter lessons`);
